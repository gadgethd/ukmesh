#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const json = name => JSON.parse(fs.readFileSync(path.join(root, 'contracts', name), 'utf8'));
const literal = value => JSON.stringify(value, null, 2);
const banner = '// Generated by scripts/generate-shared-contracts.mjs. Edit contracts/ instead.\n';
const pythonBanner = '# Generated by scripts/generate-shared-contracts.mjs. Edit contracts/ instead.\n';
const check = process.argv.includes('--check');

export function generate(publicData, link, lua) {
  if (!Array.isArray(publicData.channels) || !publicData.channels.length
    || publicData.channels.some(c => Object.keys(c).sort().join() !== 'label,slug'
      || typeof c.label !== 'string' || !/^[a-z0-9]+$/.test(c.slug)
      || c.label.toLowerCase() !== c.slug || c.slug === 'all')
    || new Set(publicData.channels.map(c => c.slug)).size !== publicData.channels.length) {
    throw new Error('Invalid public channel metadata');
  }
  const sections = publicData.statsSections;
  if (!sections || !Object.keys(sections).length || Object.values(sections).some(fields =>
    !Array.isArray(fields) || !fields.length || new Set(fields).size !== fields.length
    || fields.some(f => typeof f !== 'string' || !/^[a-zA-Z][a-zA-Z0-9]*$/.test(f)))) {
    throw new Error('Invalid stats sections');
  }
  const keys = link.keys;
  if (link.version !== 3 || !keys || Object.values(keys).some(k => !/^meshcore:link:v3:[a-z_]+$/.test(k))
    || new Set(Object.values(keys)).size !== Object.keys(keys).length
    || !Array.isArray(link.admitKeys) || link.admitKeys.some(k => !Object.hasOwn(keys, k))
    || new Set(link.admitKeys).size !== link.admitKeys.length
    || link.admitKeys.length !== 13 || link.admitArguments.length !== 9 || !lua.trim()) {
    throw new Error('Invalid link-v3 bindings');
  }
  for (const spec of Object.values(link.limits)) {
    if (!/^LINK_QUEUE_V3_[A-Z_]+$/.test(spec.env)
      || ![spec.min, spec.default, spec.max].every(Number.isSafeInteger)
      || spec.min < 1 || spec.default < spec.min || spec.default > spec.max) {
      throw new Error('Invalid link-v3 limits');
    }
  }
  const metadata = `export const PUBLIC_CHANNEL_METADATA = ${literal(publicData.channels)} as const;\n`;
  const stats = literal(sections);
  const upper = k => k.replace(/[A-Z]/g, c => `_${c}`).toUpperCase();
  const pyKeys = Object.entries(keys).map(([k, value]) => `${upper(k)} = ${JSON.stringify(value)}\n`).join('');
  return new Map([
    ['backend/src/contracts/publicData.generated.ts', banner + metadata
      + `export const CHART_SECTIONS = ${stats} as const;\n`],
    ['frontend/src/contracts/publicData.generated.ts', banner + metadata
      + `export const MESSAGE_SCOPE_CHANNELS = ${literal(publicData.channels.map(c => c.slug))} as const;\n`
      + `export const STATS_SECTION_FIELDS = ${stats} as const;\n`],
    ['backend/src/contracts/linkProtocol.generated.ts', banner
      + `export const LINK_V3_KEYS = ${literal(keys)} as const;\n`
      + `export const LINK_V3_ADMIT_KEYS = ${literal(link.admitKeys)}.map(key => LINK_V3_KEYS[key as keyof typeof LINK_V3_KEYS]);\n`
      + `export const LINK_V3_ADMIT_SCRIPT = ${JSON.stringify(lua)};\n`
      + `export const LINK_V3_LIMITS = ${literal(link.limits)} as const;\n`],
    ['viewshed-worker/link_protocol_generated.py', pythonBanner + pyKeys
      + `ADMIT_KEYS = (${link.admitKeys.map(upper).join(', ')},)\n`
      + `ADMIT_SCRIPT = ${JSON.stringify(lua)}\n`
      + `LINK_V3_LIMITS = ${literal(link.limits)}\n`],
  ]);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outputs = generate(json('public-data.json'), json('link-v3.json'),
    fs.readFileSync(path.join(root, 'contracts/link-v3-admit.lua'), 'utf8'));
  const stale = [];
  for (const [name, content] of outputs) {
    const file = path.join(root, name);
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) stale.push(name);
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
    }
  }
  if (stale.length) {
    console.error(`Shared contracts have changed; run node scripts/generate-shared-contracts.mjs:\n${stale.join('\n')}`);
    process.exitCode = 1;
  } else console.log(`Shared contracts ${check ? 'verified' : 'generated'}: ${outputs.size} package-local adapters.`);
}
